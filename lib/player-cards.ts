/**
 * Resolves the player card info for a given player name, IGN, or player ID.
 */
export function getPlayerCardInfo(nameOrId: string | null | undefined): PlayerCardInfo | null {
  if (!nameOrId || typeof nameOrId !== "string") return null;

  const query = nameOrId.trim().toLowerCase();
  if (!query) return null;

  // Clean tags like "DOMINIC#123" -> "DOMINIC"
  const cleanQuery = query.split("#")[0].trim();

  // 1. Direct match on aliases
  for (const card of PLAYER_CARDS) {
    if (card.aliases.some((alias) => alias.toLowerCase() === query || alias.toLowerCase() === cleanQuery)) {
      return card;
    }
  }

  // 2. Partial / includes match
  for (const card of PLAYER_CARDS) {
    if (
      card.aliases.some(
        (alias) => cleanQuery.includes(alias.toLowerCase()) || alias.toLowerCase().includes(cleanQuery),
      )
    ) {
      return card;
    }
  }

  // 3. Match against file name without extension
  for (const card of PLAYER_CARDS) {
    const baseName = card.fileName.replace(/\.png$/i, "").toLowerCase();
    if (cleanQuery.includes(baseName) || baseName.includes(cleanQuery)) {
      return card;
    }
  }

  return null;
}

/**
 * Quick helper returning the URL path to the player's card, or null if unmapped.
 */
export function getPlayerCardUrl(nameOrId: string | null | undefined): string | null {
  const info = getPlayerCardInfo(nameOrId);
  return info?.url || null;
}
